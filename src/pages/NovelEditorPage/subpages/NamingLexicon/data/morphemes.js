// 中式 / 西式 / 祝福包的条目构造器
const m = (pack, pos, char, pinyin, meaning, gloss, tags = []) => ({
  id: `${pack}-${pos}-${char}`,
  pack,
  pos,
  char,
  pinyin,
  meaning,
  gloss,
  tags,
})

// 古语包：id 用词根本身，避开「索尔(sol-/sól-)」「瓦尔(val-/vár-)」这类音译撞车
const a = (origin, root, pos, char, meaning, tags = []) => ({
  id: `anc-${origin}-${root}`,
  pack: 'ancient',
  origin,
  root: `${root}-`,
  pos,
  char,
  meaning,
  gloss: meaning.split('、')[0],
  tags,
})

