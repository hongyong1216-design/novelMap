// 命名库·语素表
//
// 一条语素 = 一个「可拼装的音义单元」，由公式按槽位抽取组合成名字。
//   id      唯一标识
//   char    语素本体（古语音译可能是两三个字，如「格拉」「斯泰拉」）
//   pinyin  读音（古语包用 root 代替）
//   meaning 完整释义，卡片上展示
//   gloss   组名时拼进释义的简短义（如「炽热的、燃烧的」→「炽热」）
//   pos     词性：adj 形容词性 / noun 名词性 / verb 动词性
//   pack    语素包：cn 中式单字 / west 西式音译 / bless 祝福语素 / ancient 古语词根
//   tags    语义标签，物种公式据此筛选合适的语素（见 TAGS）
//   root    古语词根原文（仅 ancient 包）
//   origin  古语来源（仅 ancient 包）：latin / greek / norse
//
// 关于同字冲突：素材里「洛」既被标为星辰又被标为森林，「薇」既是花又是冰霜。
// 这里以物种公式的示例名为准（洛=森林、薇=冰霜、艾=星辰），冲突的另一义舍弃，
// 保证一个语素在整套体系里只有一个含义。要改口径的话直接改下面的条目即可。

